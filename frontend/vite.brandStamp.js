import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { resolve, join, relative } from "node:path";

const BRAND_FILES = ["logo.png", "icon-192.png", "icon-512.png", "favicon-64.png"];

function hashBrandAssets(publicDir) {
  const hash = createHash("sha256");
  for (const name of BRAND_FILES) {
    const full = resolve(publicDir, name);
    if (existsSync(full)) hash.update(readFileSync(full));
  }
  return hash.digest("hex").slice(0, 12);
}

function hashTree(dir, hash, rootDir) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir).sort()) {
    if (name === "brandAssets.js" || name === "version.json") continue;
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) {
      hashTree(full, hash, rootDir);
      continue;
    }
    hash.update(relative(rootDir, full));
    hash.update(readFileSync(full));
  }
}

/** Content hash of app source + brand assets — changes on every real deploy. */
function hashAppBuild(rootDir, publicDir) {
  const hash = createHash("sha256");
  hashTree(resolve(rootDir, "src"), hash, rootDir);
  hashTree(publicDir, hash, rootDir);
  for (const name of ["package.json", "index.html", "vite.config.js"]) {
    const full = resolve(rootDir, name);
    if (existsSync(full)) {
      hash.update(name);
      hash.update(readFileSync(full));
    }
  }
  return hash.digest("hex").slice(0, 12);
}

function writeManifest(publicDir, brandVersion) {
  const manifestPath = resolve(publicDir, "manifest.json");
  const manifest = {
    name: "آبشده قصر طلا",
    short_name: "آبشده قصر طلا",
    description: "خرید و فروش آنلاین طلا",
    start_url: "/",
    display: "standalone",
    orientation: "portrait",
    background_color: "#12100b",
    theme_color: "#12100b",
    dir: "rtl",
    lang: "fa",
    // Changing id when icons change nudges Chromium to refresh the installed icon.
    id: `/?brand=${brandVersion}`,
    icons: [
      { src: `/favicon-64.png?v=${brandVersion}`, sizes: "64x64", type: "image/png", purpose: "any" },
      { src: `/icon-192.png?v=${brandVersion}`, sizes: "192x192", type: "image/png", purpose: "any maskable" },
      { src: `/icon-512.png?v=${brandVersion}`, sizes: "512x512", type: "image/png", purpose: "any maskable" },
      { src: `/logo.png?v=${brandVersion}`, sizes: "1254x1254", type: "image/png", purpose: "any" },
    ],
  };
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
}

function writeBrandModule(srcDir, brandVersion, buildVersion) {
  const contents = `/** Auto-generated by vite brandStamp plugin — do not edit. */
export const BRAND_V = ${JSON.stringify(brandVersion)};
export const APP_BUILD_V = ${JSON.stringify(buildVersion)};
export const logoUrl = \`/logo.png?v=\${BRAND_V}\`;
export const icon192Url = \`/icon-192.png?v=\${BRAND_V}\`;
export const icon512Url = \`/icon-512.png?v=\${BRAND_V}\`;
export const faviconUrl = \`/favicon-64.png?v=\${BRAND_V}\`;
export const manifestUrl = \`/manifest.json?v=\${BRAND_V}\`;
`;
  writeFileSync(resolve(srcDir, "brandAssets.js"), contents);
}

function writeVersionFile(dir, brandVersion, buildVersion) {
  writeFileSync(
    resolve(dir, "version.json"),
    `${JSON.stringify({ build: buildVersion, brand: brandVersion }, null, 2)}\n`
  );
}

/**
 * Stamps brand icon URLs + a content-based APP_BUILD_V so clients
 * pick up code deploys (not only logo changes) without hard refresh.
 */
export function brandStampPlugin() {
  let brandVersion = "dev";
  let buildVersion = "dev";
  let rootDir = "";
  let publicDir = "";
  return {
    name: "brand-stamp",
    configResolved(config) {
      rootDir = config.root;
      publicDir = resolve(config.root, "public");
      const srcDir = resolve(config.root, "src");
      brandVersion = hashBrandAssets(publicDir);
      buildVersion = hashAppBuild(config.root, publicDir);
      writeManifest(publicDir, brandVersion);
      writeBrandModule(srcDir, brandVersion, buildVersion);
      writeVersionFile(publicDir, brandVersion, buildVersion);
    },
    transformIndexHtml(html) {
      return html
        .replaceAll('href="/manifest.json"', `href="/manifest.json?v=${brandVersion}"`)
        .replaceAll('href="/favicon-64.png"', `href="/favicon-64.png?v=${brandVersion}"`)
        .replaceAll('href="/icon-192.png"', `href="/icon-192.png?v=${brandVersion}"`)
        .replaceAll('href="/icon-512.png"', `href="/icon-512.png?v=${brandVersion}"`)
        .replace(
          "</head>",
          `    <meta name="app-build" content="${buildVersion}" />\n  </head>`
        );
    },
    closeBundle() {
      // Ensure dist/ always has the stamped version file for deploy polling.
      const outDir = resolve(rootDir, "dist");
      if (existsSync(outDir)) {
        writeVersionFile(outDir, brandVersion, buildVersion);
      }
    },
  };
}
