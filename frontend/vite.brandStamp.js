import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync, unlinkSync } from "node:fs";
import { resolve, join, relative } from "node:path";
import { spawnSync } from "node:child_process";

const BRAND_FILES = [
  "logo.png",
  "gt-icon-192.png",
  "gt-icon-512.png",
  "gt-apple-touch-icon.png",
  "gt-favicon-64.png",
];

const LEGACY_DIST_ICONS = [
  "icon-192.png",
  "icon-512.png",
  "icon-192-maskable.png",
  "icon-512-maskable.png",
  "apple-touch-icon.png",
  "favicon-64.png",
];

function regenerateBrandIcons(rootDir) {
  const script = resolve(rootDir, "scripts/generate_brand_icons.py");
  if (!existsSync(script)) return;
  const result = spawnSync("python3", [script], { cwd: rootDir, encoding: "utf8" });
  if (result.status !== 0) {
    console.warn("[brand-stamp] icon generation failed:\n", result.stderr || result.stdout);
  } else if (result.stdout) {
    console.log(result.stdout.trim());
  }
}

function hashBrandAssets(publicDir) {
  const hash = createHash("sha256");
  for (const name of BRAND_FILES) {
    const full = resolve(publicDir, name);
    if (existsSync(full)) hash.update(readFileSync(full));
  }
  return hash.digest("hex").slice(0, 12);
}

function hashTree(dir, hash, rootDir) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir).sort()) {
    if (name === "brandAssets.js" || name === "version.json") continue;
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) {
      hashTree(full, hash, rootDir);
      continue;
    }
    hash.update(relative(rootDir, full));
    hash.update(readFileSync(full));
  }
}

/** Content hash of app source + brand assets — changes on every real deploy. */
function hashAppBuild(rootDir, publicDir) {
  const hash = createHash("sha256");
  hashTree(resolve(rootDir, "src"), hash, rootDir);
  hashTree(publicDir, hash, rootDir);
  for (const name of ["package.json", "index.html", "vite.config.js"]) {
    const full = resolve(rootDir, name);
    if (existsSync(full)) {
      hash.update(name);
      hash.update(readFileSync(full));
    }
  }
  return hash.digest("hex").slice(0, 12);
}

const ADMIN_START_URL = "/admin-hs-panel?source=pwa";

function brandIcons(brandVersion) {
  return [
    {
      src: `/gt-favicon-64.png?v=${brandVersion}`,
      sizes: "64x64",
      type: "image/png",
      purpose: "any",
    },
    {
      src: `/gt-icon-192.png?v=${brandVersion}`,
      sizes: "192x192",
      type: "image/png",
      purpose: "any",
    },
    {
      src: `/gt-icon-512.png?v=${brandVersion}`,
      sizes: "512x512",
      type: "image/png",
      purpose: "any",
    },
    {
      src: `/gt-apple-touch-icon.png?v=${brandVersion}`,
      sizes: "180x180",
      type: "image/png",
      purpose: "any",
    },
  ];
}

function writeManifest(publicDir, brandVersion) {
  const manifestPath = resolve(publicDir, "manifest.json");
  const manifest = {
    name: "آبشده قصر طلا",
    short_name: "آبشده قصر طلا",
    description: "خرید و فروش آنلاین طلا",
    start_url: "/?source=pwa",
    scope: "/",
    display: "standalone",
    orientation: "portrait",
    // Splash only. Do NOT ship maskable icons — Chrome fills those with this
    // color and produces the black circular plate on Android shortcuts.
    background_color: "#12100b",
    theme_color: "#12100b",
    dir: "rtl",
    lang: "fa",
    // Changing id when icons change nudges Chromium to refresh the installed icon.
    id: `/?brand=${brandVersion}`,
    icons: brandIcons(brandVersion),
  };
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

  // Static HTTPS URL — Safari ignores blob: manifests for Add to Home Screen.
  const adminManifestPath = resolve(publicDir, "admin-manifest.json");
  const adminManifest = {
    name: "پنل مدیریت قصر طلا",
    short_name: "پنل قصر طلا",
    description: "پنل مدیریت آبشده قصر طلا",
    start_url: ADMIN_START_URL,
    // Must prefix-match start_url (/admin-hs-panel?...) — trailing slash breaks install.
    scope: "/admin-hs-panel",
    display: "standalone",
    orientation: "portrait",
    background_color: "#12100b",
    theme_color: "#12100b",
    dir: "rtl",
    lang: "fa",
    id: `/admin-hs-panel?brand=${brandVersion}`,
    icons: brandIcons(brandVersion),
  };
  writeFileSync(adminManifestPath, `${JSON.stringify(adminManifest, null, 2)}\n`);
}

function writeBrandModule(srcDir, brandVersion, buildVersion) {
  const contents = `/** Auto-generated by vite brandStamp plugin — do not edit. */
export const BRAND_V = ${JSON.stringify(brandVersion)};
export const APP_BUILD_V = ${JSON.stringify(buildVersion)};
export const logoUrl = \`/logo.png?v=\${BRAND_V}\`;
export const icon192Url = \`/gt-icon-192.png?v=\${BRAND_V}\`;
export const icon512Url = \`/gt-icon-512.png?v=\${BRAND_V}\`;
export const faviconUrl = \`/gt-favicon-64.png?v=\${BRAND_V}\`;
export const appleTouchIconUrl = \`/gt-apple-touch-icon.png?v=\${BRAND_V}\`;
export const manifestUrl = \`/manifest.json?v=\${BRAND_V}\`;
export const adminManifestUrl = \`/admin-manifest.json?v=\${BRAND_V}\`;
`;
  writeFileSync(resolve(srcDir, "brandAssets.js"), contents);
}

function writeVersionFile(dir, brandVersion, buildVersion) {
  writeFileSync(
    resolve(dir, "version.json"),
    `${JSON.stringify({ build: buildVersion, brand: brandVersion }, null, 2)}\n`
  );
}

function purgeLegacyIcons(dir) {
  if (!existsSync(dir)) return;
  for (const name of LEGACY_DIST_ICONS) {
    const full = resolve(dir, name);
    if (existsSync(full)) {
      unlinkSync(full);
      console.log(`[brand-stamp] removed legacy ${name}`);
    }
  }
}

/**
 * Stamps brand icon URLs + a content-based APP_BUILD_V so clients
 * pick up code deploys (not only logo changes) without hard refresh.
 */
export function brandStampPlugin() {
  let brandVersion = "dev";
  let buildVersion = "dev";
  let rootDir = "";
  let publicDir = "";
  return {
    name: "brand-stamp",
    configResolved(config) {
      rootDir = config.root;
      publicDir = resolve(config.root, "public");
      const srcDir = resolve(config.root, "src");
      regenerateBrandIcons(rootDir);
      brandVersion = hashBrandAssets(publicDir);
      buildVersion = hashAppBuild(config.root, publicDir);
      writeManifest(publicDir, brandVersion);
      writeBrandModule(srcDir, brandVersion, buildVersion);
      writeVersionFile(publicDir, brandVersion, buildVersion);
    },
    transformIndexHtml(html) {
      const adminBootstrap = `<script>(function(){var p=location.pathname.replace(/\\/+$/, "")||"/";if(p!=="/admin-hs-panel")return;var link=document.querySelector('link[rel="manifest"]');if(link)link.href="/admin-manifest.json";document.title="پنل مدیریت قصر طلا";var appleTitle=document.querySelector('meta[name="apple-mobile-web-app-title"]');if(appleTitle)appleTitle.content="پنل قصر طلا";var appleIcon=document.querySelector('link[rel="apple-touch-icon"]');if(appleIcon)appleIcon.href="/gt-apple-touch-icon.png";})();</script>`;
      return html
        .replaceAll('href="/manifest.json"', `href="/manifest.json?v=${brandVersion}"`)
        .replaceAll('href="/gt-favicon-64.png"', `href="/gt-favicon-64.png?v=${brandVersion}"`)
        .replaceAll('href="/gt-icon-192.png"', `href="/gt-icon-192.png?v=${brandVersion}"`)
        .replaceAll('href="/gt-icon-512.png"', `href="/gt-icon-512.png?v=${brandVersion}"`)
        // iOS A2HS reads apple-touch-icon literally — keep a stable URL without query args.
        .replaceAll(
          'href="/gt-apple-touch-icon.png"',
          'href="/gt-apple-touch-icon.png"'
        )
        .replace(
          `<link rel="manifest" href="/manifest.json?v=${brandVersion}" />`,
          `<link rel="manifest" href="/manifest.json?v=${brandVersion}" />\n    ${adminBootstrap}`
        )
        .replace(
          "</head>",
          `    <meta name="app-build" content="${buildVersion}" />\n  </head>`
        );
    },
    closeBundle() {
      // Ensure dist/ always has the stamped version file for deploy polling.
      const outDir = resolve(rootDir, "dist");
      if (existsSync(outDir)) {
        writeVersionFile(outDir, brandVersion, buildVersion);
        purgeLegacyIcons(outDir);
      }
    },
  };
}
