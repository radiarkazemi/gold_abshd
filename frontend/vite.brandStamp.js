import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

const BRAND_FILES = ["logo.png", "icon-192.png", "icon-512.png", "favicon-64.png"];

function hashBrandAssets(publicDir) {
  const hash = createHash("sha256");
  for (const name of BRAND_FILES) {
    const full = resolve(publicDir, name);
    if (existsSync(full)) hash.update(readFileSync(full));
  }
  return hash.digest("hex").slice(0, 12);
}

function writeManifest(publicDir, version) {
  const manifestPath = resolve(publicDir, "manifest.json");
  const manifest = {
    name: "آبشده قصر طلا",
    short_name: "آبشده قصر طلا",
    description: "خرید و فروش آنلاین طلا",
    start_url: "/",
    display: "standalone",
    orientation: "portrait",
    background_color: "#12100b",
    theme_color: "#12100b",
    dir: "rtl",
    lang: "fa",
    // Changing id when icons change nudges Chromium to refresh the installed icon.
    id: `/?brand=${version}`,
    icons: [
      { src: `/favicon-64.png?v=${version}`, sizes: "64x64", type: "image/png", purpose: "any" },
      { src: `/icon-192.png?v=${version}`, sizes: "192x192", type: "image/png", purpose: "any maskable" },
      { src: `/icon-512.png?v=${version}`, sizes: "512x512", type: "image/png", purpose: "any maskable" },
      { src: `/logo.png?v=${version}`, sizes: "1254x1254", type: "image/png", purpose: "any" },
    ],
  };
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
}

function writeBrandModule(srcDir, version) {
  const contents = `/** Auto-generated by vite brandStamp plugin — do not edit. */
export const BRAND_V = ${JSON.stringify(version)};
export const logoUrl = \`/logo.png?v=\${BRAND_V}\`;
export const icon192Url = \`/icon-192.png?v=\${BRAND_V}\`;
export const icon512Url = \`/icon-512.png?v=\${BRAND_V}\`;
export const faviconUrl = \`/favicon-64.png?v=\${BRAND_V}\`;
export const manifestUrl = \`/manifest.json?v=\${BRAND_V}\`;
`;
  writeFileSync(resolve(srcDir, "brandAssets.js"), contents);
}

/**
 * Stamps brand icon URLs with a content hash so PWA / home-screen /
 * in-app logos refresh when logo.png (or related icons) change.
 */
export function brandStampPlugin() {
  let version = "dev";
  return {
    name: "brand-stamp",
    configResolved(config) {
      const publicDir = resolve(config.root, "public");
      const srcDir = resolve(config.root, "src");
      version = hashBrandAssets(publicDir);
      writeManifest(publicDir, version);
      writeBrandModule(srcDir, version);
    },
    transformIndexHtml(html) {
      return html
        .replaceAll('href="/manifest.json"', `href="/manifest.json?v=${version}"`)
        .replaceAll('href="/favicon-64.png"', `href="/favicon-64.png?v=${version}"`)
        .replaceAll('href="/icon-192.png"', `href="/icon-192.png?v=${version}"`)
        .replaceAll('href="/icon-512.png"', `href="/icon-512.png?v=${version}"`);
    },
  };
}
